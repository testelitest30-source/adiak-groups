#!/usr/bin/env python3
"""Generates supabase/rollback/batchA_{disable,enable}.sql.
disable: restores the 7 existing functions + messages policy changed by M4 byte-for-byte from supabase/baseline,
revokes client access to the new RPCs, disables the new triggers and sets app_settings.pres_enabled=false.
NO table, row or file is dropped or deleted. enable: re-applies M4 and the grants/triggers."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
base = ''.join(p.read_text() for p in sorted((root/'supabase/baseline').glob('0[2-5]_*.sql')))
def fn(name):
    m = re.search(r'CREATE OR REPLACE FUNCTION public\.%s\(.*?\$function\$\n;' % re.escape(name), base, re.S)
    assert m, name; return m.group(0)
pol = re.search(r'create policy r on public\.messages .*?\)\)\);', (root/'supabase/baseline/06_triggers_policies_grants.sql').read_text(), re.S).group(0)
FUNCS = ['_chan_ok','_chtag','send_message','admin_close_day','admin_set_perms','admin_set_staff','staff_classes']
TRIG = [('notifications','tg_note_outbox'),('messages','tg_msg_outbox'),('profiles','tg_pres_membership'),('groups','tg_pres_group_deleted'),
        ('requests','tg_n_requests'),('invites','tg_n_invites'),('kicks','tg_n_kicks'),('point_events','tg_n_points'),
        ('user_tags','tg_n_tags'),('profiles','tg_n_membership'),('messages','tg_n_mentions')]
REVOKE = """do $$ declare f record; begin
  for f in select p.oid::regprocedure sig from pg_proc p where p.pronamespace = 'public'::regnamespace
     and (p.proname like 'pres\\_%' or p.proname like 'live\\_%' or p.proname like 'notes\\_%' or p.proname like 'class\\_%' or p.proname like 'assignment\\_%'
          or p.proname like 'ops\\_%' or p.proname like 'owner\\_%' or p.proname in ('save_fcm','drop_fcm','server_now','my_access','teacher_home'))
     and p.proname <> 'pres_due_reminders'
  loop execute format('revoke execute on function %s from authenticated', f.sig); end loop; end $$;"""
GRANT = REVOKE.replace("revoke execute on function %s from authenticated", "grant execute on function %s to authenticated")
d = ["-- ADIAK 1.0 batch A: NON-DESTRUCTIVE disable (generated by scripts/gen-rollback.py). Keeps every new table, row and file.",
     "begin;"]
d += [fn(f) for f in FUNCS]
d += ["drop policy r on public.messages;", pol, REVOKE]
d += ["alter table public.%s disable trigger %s;" % t for t in TRIG]
d += ["insert into public.app_settings(key, value) values ('pres_enabled', 'false') on conflict (key) do update set value = 'false';",
      "commit;"]
(root/'supabase/rollback/batchA_disable.sql').write_text('\n'.join(d) + '\n')
m4 = (root/'supabase/migrations/20261109100300_existing_additive.sql').read_text()
m4 = m4[m4.index('-- may user u post to'):]
e = ["-- ADIAK 1.0 batch A: re-enable after batchA_disable.sql (generated by scripts/gen-rollback.py).", "begin;", m4, GRANT]
e += ["alter table public.%s enable trigger %s;" % t for t in TRIG]
e += ["delete from public.app_settings where key = 'pres_enabled';", "commit;"]
(root/'supabase/rollback/batchA_enable.sql').write_text('\n'.join(e) + '\n')
print('ok')
